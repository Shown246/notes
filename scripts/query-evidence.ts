import { mkdir, writeFile } from 'node:fs/promises';

type RecordValue = Record<string, unknown>;
const record = (value: unknown): RecordValue => value && typeof value === 'object' ? value as RecordValue : {};

// Traverse only winning/executed plans, never rejected alternatives, when
// reporting selected index names and blocking stages.
function planValues(value: unknown, key: string): string[] {
  const values = new Set<string>();
  function visit(item: unknown) {
    if (!item || typeof item !== 'object') return;
    for (const [name, child] of Object.entries(item)) {
      if (['rejectedPlans', 'allPlansExecution', 'command'].includes(name)) continue;
      if (name === key && typeof child === 'string') values.add(child);
      else visit(child);
    }
  }
  visit(value);
  return [...values];
}

export async function saveEvidence(name: string, databaseName: string, evidence: RecordValue) {
  const sanitized = JSON.stringify(evidence, (key: string, value: unknown) => {
    if (['serverInfo', 'serverParameters', 'operationTime', '$clusterTime'].includes(key)) return undefined;
    if (typeof value === 'string') return value.replaceAll(databaseName, 'notes_explain_fixture');
    return value;
  }, 2);
  const clean = JSON.parse(sanitized) as RecordValue;
  const lines = [
    `# ${name} query evidence`, '',
    `Recorded: ${clean.recordedAt}; MongoDB ${clean.mongodbVersion}. Generated by \`npm run db:explain\`.`, '',
    String(clean.notes), '',
    'Fixture: ' + JSON.stringify(clean.fixtures), '',
    '| Case | Selected index(es) | Returned | Keys | Documents | Execution ms | Blocking / scan |',
    '| --- | --- | ---: | ---: | ---: | ---: | --- |'
  ];
  const observations: string[] = [];
  function summarize(label: string, value: unknown) {
    const explain = record(value);
    if (!explain.queryPlanner && !explain.stages) {
      for (const [key, child] of Object.entries(explain)) if (key !== 'pipeline' && key !== 'measurement' && key !== 'options') summarize(`${label}.${key}`, child);
      return;
    }
    const stages = Array.isArray(explain.stages) ? explain.stages.map(record) : [];
    const cursor = stages.find(stage => stage.$cursor)?.$cursor;
    const stats = record(record(cursor ?? explain).executionStats);
    const indexes = planValues(explain, 'indexName');
    const blocking = planValues(explain, 'stage').filter(stage => ['SORT', 'COLLSCAN'].includes(stage));
    for (const stage of stages) {
      if (stage.$group) blocking.push('$group');
      if (stage.$sort) blocking.push('$sort');
    }
    lines.push(`| ${label} | ${indexes.join(', ') || 'none'} | ${stats.nReturned ?? 'n/a'} | ${stats.totalKeysExamined ?? 'n/a'} | ${stats.totalDocsExamined ?? 'n/a'} | ${stats.executionTimeMillis ?? 'n/a'} | ${blocking.join(', ') || 'none'} |`);
    for (const stage of stages) {
      if (stage.$lookup) observations.push(`${label} foreign lookup: ${JSON.stringify({
        indexesUsed: stage.indexesUsed, totalKeysExamined: stage.totalKeysExamined,
        totalDocsExamined: stage.totalDocsExamined, collectionScans: stage.collectionScans,
        executionTimeMillisEstimate: stage.executionTimeMillisEstimate
      })}`);
      if (stage.$group || stage.$sort) observations.push(`${label} ${stage.$group ? '$group' : '$sort'}: ${JSON.stringify(
        Object.fromEntries(Object.entries(stage).filter(([key]) => !key.startsWith('$')))
      )}`);
    }
  }
  for (const [label, value] of Object.entries(record(clean.cases))) summarize(label, value);
  const measurements = Object.entries(record(clean.cases)).flatMap(([label, value]) => {
    const measurement = record(value).measurement;
    return measurement ? [`- ${label} aggregate and cursor measurement: ${JSON.stringify(measurement)}`] : [];
  });
  const explanation = name === 'interests'
    ? 'Both report modes use allowDiskUse, a 5000 ms budget and binary collation. Paginated groups retain at most five previews through $topN. The all case retains every member through $push and has no group limit. Its result documents remain subject to the BSON size limit and its arrays to aggregation memory limits. The interests range is applied before unwind for indexed user selection; paginated queries repeat it after unwind for exact membership filtering. Selective cursor pages can avoid irrelevant users; broad first-page and complete plans may still prefer a collection scan. Group counts and computed sorting still require processing memberships. Accumulator memory is not total process memory; disk permission does not remove aggregation limits.'
    : name === 'posts'
      ? 'The production author pipeline is reused directly. Post IDs interleave authors; the cursor is halfway through the target author. The actual lookup statistics establish foreign index use; the supplemental foreign find exposes index-backed ordering because MongoDB does not expose the full foreign winning tree in the lookup summary. Its extra reads run only in developer tooling.'
      : 'The measured owner-scoped point read chooses notes_owner_id_desc on this server. The built-in _id_ also supports an exact-ID candidate followed by ownership verification; either existing index satisfies this bound. No hint or extra index is needed. The denied-owner case returns zero rows. Each ordinary page fetches 21 for a 20-row response.';
  lines.push('', 'Table metrics describe the root find or the aggregation input cursor. Foreign lookup and blocking-stage observations follow; full commands, pipelines and all statistics are in the JSON.', '',
    ...observations.map(value => `- ${value}`), ...measurements, '', explanation, '',
    'Timings are local single-run observations, not guarantees. Missing spill metrics mean the server did not expose them, not proof of zero memory use. Broad interest pages may scan; ordinary pages should avoid scans and blocking sorts on this fixture. Planner tree layouts may vary with MongoDB versions.', '',
    `[Full sanitized evidence](${name}.json)`, '');
  await mkdir('docs/query-evidence', { recursive: true });
  await writeFile(`docs/query-evidence/${name}.json`, `${sanitized}\n`);
  await writeFile(`docs/query-evidence/${name}.md`, lines.join('\n'));
  process.stdout.write(`Saved disposable-fixture ${name} evidence.\n`);
}
